"""Render findings as a table, JSON or a list of gcloud cleanup commands."""

from __future__ import annotations

import json
from typing import Any

from .checks import CHECKS, Finding

TITLES = {
    "disks": "Unattached disks",
    "addresses": "Unused static IP addresses",
    "snapshots": "Old snapshots",
    "instances": "Stopped or suspended VMs (still billed for disks and static IPs)",
}


def _money(value: float | None, currency: str) -> str:
    if value is None:
        return "-"
    sign = "$" if currency == "USD" else f"{currency} "
    return f"{sign}{value:,.2f}"


def _table(rows: list[list[str]], indent: str = "  ") -> list[str]:
    widths = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
    lines = []
    for r in rows:
        cells = [c.ljust(widths[i]) for i, c in enumerate(r[:-1])] + [r[-1]]
        lines.append(indent + "  ".join(cells).rstrip())
    return lines


def totals(findings: list[Finding]) -> dict[str, Any]:
    by_check: dict[str, dict[str, Any]] = {}
    for f in findings:
        t = by_check.setdefault(f.check, {"count": 0, "monthly_cost": 0.0})
        t["count"] += 1
        t["monthly_cost"] = round(t["monthly_cost"] + (f.monthly_cost or 0), 2)
    return {
        "count": len(findings),
        "monthly_cost": round(sum(f.monthly_cost or 0 for f in findings), 2),
        "by_check": by_check,
    }


def render_table(findings: list[Finding], loaded: list[str], prices: dict[str, Any]) -> str:
    cur = prices.get("currency", "USD")
    out: list[str] = []
    for check in CHECKS:
        if check not in loaded:
            continue
        group = [f for f in findings if f.check == check]
        out.append(f"{TITLES[check]}: {len(group)}")
        if group:
            rows = [["NAME", "LOCATION", "PER MONTH", "WHY"]]
            rows += [[f.name, f.location, _money(f.monthly_cost, cur), f.reason] for f in group]
            out.extend(_table(rows))
        out.append("")
    t = totals(findings)
    out.append(f"Total: {t['count']} finding(s), estimated {_money(t['monthly_cost'], cur)}/month "
               "(example prices; see --prices)")
    skipped = [c for c in CHECKS if c not in loaded]
    if skipped:
        out.append(f"Not checked (no input file): {', '.join(skipped)}")
    out.append("Read-only: nothing was changed. Use --format commands to list cleanup commands to review.")
    return "\n".join(out)


def render_json(findings: list[Finding], loaded: list[str], prices: dict[str, Any], now_iso: str) -> str:
    doc = {
        "generated_at": now_iso,
        "checked": loaded,
        "currency": prices.get("currency", "USD"),
        "price_note": "estimates use example default prices unless --prices was given",
        "totals": totals(findings),
        "findings": [f.to_dict() for f in findings],
    }
    return json.dumps(doc, indent=2)


def render_commands(findings: list[Finding]) -> str:
    out = [
        "# Cleanup commands generated by gcp-idle-resources. NOT executed.",
        "# Review every line. Deletion is permanent; snapshot a disk first if you may need its data.",
    ]
    for check in CHECKS:
        group = [f for f in findings if f.check == check]
        if not group:
            continue
        out.append("")
        out.append(f"# {TITLES[check]}")
        for f in group:
            if check == "instances" and f.details.get("autoDeleteDisks"):
                out.append(f"# {f.name}: deleting it also deletes auto-delete disk(s) "
                           f"{', '.join(f.details['autoDeleteDisks'])}")
            out.append(f.command)
    return "\n".join(out)
